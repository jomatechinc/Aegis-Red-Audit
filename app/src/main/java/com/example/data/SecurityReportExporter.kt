package com.example.data

import android.content.Context
import android.content.Intent
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object SecurityReportExporter {

    fun generateAssetReportMarkdown(
        asset: Asset,
        scan: Scan?,
        findings: List<ScanFinding>,
        intel: ThreatIntelResult?
    ): String {
        val sb = StringBuilder()
        sb.appendLine("# EXECUTIVE SECURITY AUDIT REPORT")
        sb.appendLine("=========================================")
        sb.appendLine("**Target Asset:** ${asset.name}")
        sb.appendLine("**Domain / IP:** ${asset.url}")
        sb.appendLine("**Category:** ${asset.category}")
        sb.appendLine("**Tags:** ${asset.tags}")
        sb.appendLine("**Report Timestamp:** ${SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())}")
        sb.appendLine()

        if (scan != null) {
            sb.appendLine("## AUDIT SUMMARY")
            sb.appendLine("- **Scan Type:** ${scan.scanType}")
            sb.appendLine("- **Severity Verdict:** ${scan.severityLevel}")
            sb.appendLine("- **Risk Score:** ${scan.riskScore} / 100")
            sb.appendLine()
        }

        if (intel != null) {
            sb.appendLine("## REAL-TIME THREAT INTELLIGENCE FEED")
            sb.appendLine("- **Reputation Verdict:** ${intel.reputationVerdict}")
            sb.appendLine("- **AbuseIPDB Confidence Score:** ${intel.abuseScore}% (${intel.totalReports} reports)")
            sb.appendLine("- **VirusTotal Engine Detections:** ${intel.virusTotalMaliciousCount} engines flagged")
            sb.appendLine("- **Sensor Log:** ${intel.scannerDetails}")
            sb.appendLine()
        }

        sb.appendLine("## VULNERABILITY FINDINGS (${findings.size})")
        if (findings.isEmpty()) {
            sb.appendLine("No active vulnerabilities or missing headers detected during this audit.")
        } else {
            findings.forEachIndexed { idx, finding ->
                sb.appendLine("### ${idx + 1}. [${finding.severity}] ${finding.title}")
                sb.appendLine("- **Category:** ${finding.category}")
                sb.appendLine("- **Description:** ${finding.description}")
                sb.appendLine("- **Remediation Recommendation:** ${finding.recommendation}")
                sb.appendLine()
            }
        }

        sb.appendLine("---")
        sb.appendLine("Generated by Aegis Red Audit — Defensive Ethical Security Engine")
        return sb.toString()
    }

    fun generateFleetSummaryReport(
        assets: List<Asset>,
        scans: List<Scan>
    ): String {
        val sb = StringBuilder()
        sb.appendLine("# MASTER DEFENSIVE FLEET AUDIT REPORT")
        sb.appendLine("=========================================")
        sb.appendLine("**Total Assets Monitored:** ${assets.size}")
        sb.appendLine("**Total Scans Executed:** ${scans.size}")
        sb.appendLine("**Report Timestamp:** ${SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())}")
        sb.appendLine()

        sb.appendLine("## ASSET RISK PROFILE SUMMARY")
        assets.forEach { asset ->
            val latestScan = scans.filter { it.assetId == asset.id }.maxByOrNull { it.timestamp }
            val riskText = latestScan?.let { "Risk ${it.riskScore}% (${it.severityLevel})" } ?: "Unscanned"
            sb.appendLine("- **${asset.name}** (`${asset.url}`): $riskText")
        }

        sb.appendLine()
        sb.appendLine("---")
        sb.appendLine("Generated by Aegis Red Audit — Defensive Ethical Security Engine")
        return sb.toString()
    }

    fun shareReport(context: Context, title: String, content: String) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, title)
            putExtra(Intent.EXTRA_TEXT, content)
        }
        val chooser = Intent.createChooser(intent, "Export Security Audit Report")
        context.startActivity(chooser)
    }
}
